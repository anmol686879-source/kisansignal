import { DatabaseSync } from 'node:sqlite';
import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import pg from 'pg';

export function openDb(file) {
  if (file !== ':memory:') mkdirSync(dirname(file), { recursive: true });
  const db = new DatabaseSync(file);
  db.exec(`
    PRAGMA journal_mode = WAL;
    PRAGMA foreign_keys = ON;
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER PRIMARY KEY, phone TEXT NOT NULL UNIQUE,
      name TEXT, region TEXT, crop TEXT, lang TEXT,
      created INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS otps (
      phone TEXT PRIMARY KEY, hash TEXT NOT NULL, expires INTEGER NOT NULL,
      tries INTEGER NOT NULL, last_sent INTEGER NOT NULL,
      hour_start INTEGER NOT NULL, hour_count INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS sessions (
      hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS fields (
      user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      json TEXT NOT NULL, updated INTEGER NOT NULL
    );
  `);
  return {
    prepare: (sql) => db.prepare(sql),
    ping: () => db.prepare('SELECT 1').get(),
    close: () => db.close(),
  };
}

export async function openPostgresDb(connectionString) {
  const pool = new pg.Pool({
    connectionString,
    max: 5,
    connectionTimeoutMillis: 10000,
    idleTimeoutMillis: 30000,
  });
  try {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        phone TEXT NOT NULL UNIQUE,
        name TEXT, region TEXT, crop TEXT, lang TEXT,
        created BIGINT NOT NULL
      );
      CREATE TABLE IF NOT EXISTS otps (
        phone TEXT PRIMARY KEY, hash TEXT NOT NULL, expires BIGINT NOT NULL,
        tries INTEGER NOT NULL, last_sent BIGINT NOT NULL,
        hour_start BIGINT NOT NULL, hour_count INTEGER NOT NULL
      );
      CREATE TABLE IF NOT EXISTS sessions (
        hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        expires BIGINT NOT NULL
      );
      CREATE TABLE IF NOT EXISTS fields (
        user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
        json TEXT NOT NULL, updated BIGINT NOT NULL
      );
    `);
  } catch (error) {
    await pool.end();
    throw error;
  }

  const toPostgres = (sql) => {
    let index = 0;
    return sql.replace(/\?/g, () => `$${++index}`);
  };
  return {
    prepare(sql) {
      const statement = toPostgres(sql);
      return {
        async get(...params) {
          const result = await pool.query(statement, params);
          return result.rows[0];
        },
        async run(...params) {
          const result = await pool.query(statement, params);
          return { changes: result.rowCount };
        },
      };
    },
    async ping() {
      await pool.query('SELECT 1');
    },
    close: () => pool.end(),
  };
}
